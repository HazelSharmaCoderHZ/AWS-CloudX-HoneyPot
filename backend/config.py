"""HaaS backend configuration.

Reads all settings from environment variables with safe defaults.
LocalStack is the default mode. Credentials come from the standard
AWS credential chain only - never hardcoded here.
"""

import os


def _env(name, default=None):
    return os.environ.get(name, default)


# ── Mode ────────────────────────────────────────────────────────────────────
# local  → LocalStack (default). boto3 uses AWS_ENDPOINT_URL.
# real   → Real AWS account. Uses the standard credential chain.
AWS_MODE = _env("AWS_MODE", "local")
if AWS_MODE not in ("local", "real"):
    raise SystemExit(f"Unknown AWS_MODE '{AWS_MODE}'. Expected 'local' or 'real'.")

# ── AWS region ──────────────────────────────────────────────────────────────
AWS_REGION = _env("AWS_REGION", "us-east-1")

# ── Endpoint URL ────────────────────────────────────────────────────────────
# In local mode: defaults to http://localhost:4566 when running outside
# Docker, or http://localstack:4566 inside Docker (set via env).
# In real mode: None (use the default AWS endpoint).
AWS_ENDPOINT_URL = _env("AWS_ENDPOINT_URL") if AWS_MODE == "local" else None

# ── Resource names (kept identical across local & real modes) ────────────────
HAA_S3_BUCKET = _env("HAA_S3_BUCKET", "honeypot-logs-2025")
HAA_DYNAMODB_TABLE = _env("HAA_DYNAMODB_TABLE", "CowrieLogs")
HAA_IAM_ROLE = _env("HAA_IAM_ROLE", "lambda-exec-role")
HAA_PARSER_LAMBDA = _env("HAA_PARSER_LAMBDA", "CowrieLogParser")
HAA_CLOUDWATCH_LAMBDA = _env("HAA_CLOUDWATCH_LAMBDA", "LogDynamoDBToCloudWatch")

# ── Lambda runtime ──────────────────────────────────────────────────────────
HAA_LAMBDA_RUNTIME = _env("HAA_LAMBDA_RUNTIME", "python3.11")
HAA_LAMBDA_TIMEOUT = int(_env("HAA_LAMBDA_TIMEOUT", "30"))
HAA_LAMBDA_BATCH_SIZE = int(_env("HAA_LAMBDA_BATCH_SIZE", "10"))

# ── Backend runtime ─────────────────────────────────────────────────────────
BACKEND_HOST = _env("BACKEND_HOST", "0.0.0.0")
BACKEND_PORT = int(_env("BACKEND_PORT", "8000"))

# ── Data source label (shown by the UI so mock/demo data is never mistaken
# for real data) ─────────────────────────────────────────────────────────────
DATA_SOURCE_LABEL = (
    "MOCK/DEMO DATA - synthetic Cowrie attack log generated by seed.py"
    if AWS_MODE == "local"
    else "REAL AWS DATA - live Cowrie honeypot pipeline"
)